package com.mydaypedia.backend.song;

/** 작곡가/작사가를 여러 명 골라 검색할 때의 조합 방식. */
public enum CreditMatch {
    /** 고른 사람 중 한 명이라도 참여한 곡 (원필, 성진 → 원필 곡 + 성진 곡) */
    ANY,
    /** 고른 사람이 전부 참여한 곡 (원필, 성진 → 둘이 같이 쓴 곡) */
    ALL,
    /**
     * 고른 사람이 전부 참여했고, 같은 그룹의 다른 멤버는 참여하지 않은 곡. 외부 작곡가는 있어도 된다.
     * (원필, 성진 → '홍지상, 성진, 원필'은 포함 / '홍지상, 성진, Young K, 원필'은 제외)
     * 멤버 여부는 그룹 크레딧의 구성원(Songwriter.members)으로 판단하고, 그룹 크레딧('DAY6 (데이식스)')은 전원 참여로 보아 제외한다.
     */
    EXACT
}
